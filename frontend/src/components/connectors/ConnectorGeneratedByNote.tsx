"use client"

import { useEffect, useState } from "react"

import { fetchMCPConnector } from "@/lib/api/mcp-connectors"
import type { MCPConnector } from "@/lib/types/mcp-connector"

type GeneratedBy = NonNullable<MCPConnector["generated_by"]>

// generatedByLine tells the person about to give a connector credentials that
// an AI agent wrote its code (docs/internal/ask-rsync-and-mcp-roadmap.md §2.2).
export function generatedByLine(g: GeneratedBy): string {
  const when = new Date(g.generated_at)
  const date = Number.isNaN(when.getTime()) ? "" : ` on ${when.toLocaleDateString()}`
  const who = g.by ? ` (${g.by})` : ""
  return `Generated by an AI agent${who}${date}. Review it before you give it credentials.`
}

/**
 * The "Generated by an AI agent" line, for every form that takes a connector's
 * credentials. Only the single-connector read carries `generated_by`
 * (GET /api/v1/connectors/:name); a surface that holds a record from the
 * catalog list passes `lookUp` and the note reads it itself.
 */
export function ConnectorGeneratedByNote({
  connector,
  lookUp = false,
  className = "",
}: {
  connector: Pick<MCPConnector, "name" | "generated_by">
  lookUp?: boolean
  className?: string
}) {
  const [fetched, setFetched] = useState<{ name: string; generatedBy?: GeneratedBy } | null>(null)
  const needsLookUp = lookUp && !connector.generated_by

  useEffect(() => {
    if (!needsLookUp || !connector.name) return
    let live = true
    fetchMCPConnector(connector.name).then(
      (full) => {
        if (live) setFetched({ name: connector.name, generatedBy: full.generated_by })
      },
      // The line is a courtesy: a failed read leaves the form as it was.
      () => {},
    )
    return () => {
      live = false
    }
  }, [needsLookUp, connector.name])

  const g = connector.generated_by ?? (fetched?.name === connector.name ? fetched.generatedBy : undefined)
  if (!g?.generated_by_agent) return null
  return (
    <p className={`text-xs text-amber-700 dark:text-amber-400 ${className}`} data-testid="connector-generated-by">
      {generatedByLine(g)}
    </p>
  )
}
