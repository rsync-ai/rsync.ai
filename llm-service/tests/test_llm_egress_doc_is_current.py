"""docs/security/llm-egress.md must be what its generator writes today.

The page is the published answer to "what does rsync.ai send to an LLM". It is
rendered by scripts/gen_llm_egress_doc.py from the code that enforces the
answer: the call-site census, the field classes, the fixed checks, each
prompt's ``llm_fields`` and the Go boundary test's exceptions. A committed copy
goes stale the moment one of those changes; this suite regenerates the page
and fails if the committed copy differs.

Its subject is markdown AND code, so it runs in doc-links.yml's unfiltered
Doc guards job, like test_connector_reference_matches_disk.py: a prompt change
never touches the page, and a hand edit to the page touches no code. The
generator needs only the stdlib and PyYAML, which is all that job installs.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
SCRIPT = REPO / "scripts" / "gen_llm_egress_doc.py"
DOC = REPO / "docs" / "security" / "llm-egress.md"
EXCLUDES = REPO / "scripts" / "flip" / "excludes.txt"


@pytest.fixture(scope="module")
def gen():
    spec = importlib.util.spec_from_file_location("llm_egress_doc_gen", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def rendered(gen):
    return gen.render()


def test_the_committed_page_is_what_the_generator_writes(rendered):
    assert DOC.read_text() == rendered, (
        "docs/security/llm-egress.md is stale: what llm-service sends to a model changed "
        "and the published page did not. Run `python3 scripts/gen_llm_egress_doc.py` and "
        "commit the result; never edit the page by hand."
    )


def test_the_page_names_every_call_site_class_and_prompt(gen, rendered):
    # Control for the test above: a generator that rendered nothing, or dropped a
    # section, would still match a page generated by the same broken code.
    sites = gen._load_call_sites()
    classes, _ = gen.field_classes()
    assert len(sites.CALL_SITES) >= 10 and len(classes) >= 10
    for component in sites.CALL_SITES:
        assert f"| `{component}` |" in rendered, component
    for name, description in classes:
        assert f"| `{name}` |" in rendered and description, name
    for site in sites.CALL_SITES.values():
        for prompt in site.prompts:
            assert f"[`{prompt}`]" in rendered, prompt
    for prompt in sites.REFUSED_PROMPTS:
        assert f"`prompts/{prompt}.yaml`" in rendered, prompt


def test_a_class_the_docstring_does_not_describe_stops_the_generator(gen, monkeypatch, tmp_path):
    # The class table comes from fields.py's docstring; FIELD_CLASSES is what the
    # guard enforces. If they disagree the page would describe a guard that is not
    # there, so the generator refuses instead of rendering.
    fields = tmp_path / "fields.py"
    src = (gen.EGRESS / "fields.py").read_text()
    fields.write_text(src.replace('    "evidence",\n)', '    "evidence",\n    "row_values",\n)', 1))
    assert fields.read_text() != src, "the FIELD_CLASSES tuple moved; update this mutation"
    (tmp_path / "stages.py").write_text((gen.EGRESS / "stages.py").read_text())
    monkeypatch.setattr(gen, "EGRESS", tmp_path)
    with pytest.raises(SystemExit, match="row_values"):
        gen.field_classes()


def test_the_page_and_its_generator_ship_in_the_public_tree():
    if not EXCLUDES.exists():
        # The cut deletes its own list, so this is the public tree: the check is
        # that both files are here.
        missing = [p.relative_to(REPO).as_posix() for p in (DOC, SCRIPT) if not p.exists()]
        assert not missing, f"missing from the public tree: {missing}"
        return
    entries = [
        line.strip()
        for line in EXCLUDES.read_text().splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    for path in ("docs/security/llm-egress.md", "scripts/gen_llm_egress_doc.py"):
        cut = [e for e in entries if path == e.rstrip("/") or path.startswith(e.rstrip("/") + "/")]
        assert not cut, f"scripts/flip/excludes.txt removes {path} from the public tree ({cut})"
